import 'dart:io';

import 'package:dual_sub_merge/models/match_group.dart';
import 'package:dual_sub_merge/models/merge_options.dart';
import 'package:dual_sub_merge/models/process_mode.dart';
import 'package:dual_sub_merge/services/file_matcher.dart';
import 'package:dual_sub_merge/services/merge_service.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;

void main() {
  test(
    'overlapping scan directories do not duplicate extracted subtitles',
    () async {
      final root = await Directory.systemTemp.createTemp('matcher-overlap-');
      addTearDown(() => root.delete(recursive: true));
      final extract = Directory(p.join(root.path, 'dual-sub-merge-extract'));
      await extract.create();
      await File(
        p.join(extract.path, 'Arcane.S01E01.chs.srt'),
      ).writeAsString('1\n00:00:01,000 --> 00:00:02,000\n你好\n');
      await File(
        p.join(extract.path, 'Arcane.S01E01.eng.srt'),
      ).writeAsString('1\n00:00:01,000 --> 00:00:02,000\nHello\n');

      final groups = await FileMatcher.scanDirectories([root, extract]);

      expect(groups, hasLength(1));
      expect(groups.single.kind, GroupKind.pair);
      expect(groups.single.status, GroupStatus.ready);
    },
  );

  test(
    'pairs bracketed language tracks with different track numbers',
    () async {
      final root = await Directory.systemTemp.createTemp('matcher-bracketed-');
      addTearDown(() => root.delete(recursive: true));
      const stems = [
        'Slow.Horses.S05E05.Circus.2160p.ATVP.WEB-DL.DDP5.1.Atmos.H.265-FLUX',
        'Slow.Horses.S05E06.Scars.2160p.ATVP.WEB-DL.DDP5.1.Atmos.H.265-FLUX',
      ];
      final files = <File>[];
      for (final stem in stems) {
        files.add(
          await File(
            p.join(root.path, '$stem.t8.[chi].srt'),
          ).writeAsString('1\n00:00:01,000 --> 00:00:02,000\n你好，世界。\n'),
        );
        files.add(
          await File(
            p.join(root.path, '$stem.t4.[eng].srt'),
          ).writeAsString('1\n00:00:01,000 --> 00:00:02,000\nHello, world.\n'),
        );
      }

      final groups = await FileMatcher.scanFiles(files);

      expect(groups, hasLength(2));
      expect(
        groups.every((group) => group.status == GroupStatus.ready),
        isTrue,
      );
      expect(groups.every((group) => group.chinese != null), isTrue);
      expect(groups.every((group) => group.foreign != null), isTrue);
    },
  );

  test(
    'merge uses explicitly selected subtitle files without rescanning siblings',
    () async {
      final root = await Directory.systemTemp.createTemp('matcher-files-');
      addTearDown(() => root.delete(recursive: true));
      final chs = File(p.join(root.path, 'Arcane.S01E01.chs.srt'));
      final eng = File(p.join(root.path, 'Arcane.S01E01.eng.srt'));
      await chs.writeAsString('1\n00:00:01,000 --> 00:00:02,000\n你好\n');
      await eng.writeAsString('1\n00:00:01,000 --> 00:00:02,000\nHello\n');
      await File(
        p.join(root.path, 'Arcane.S01E01.chs.ass'),
      ).writeAsString('[Script Info]\n[V4+ Styles]\n[Events]\n');
      final groups = await FileMatcher.scanFiles([chs, eng]);
      final output = Directory(p.join(root.path, 'output'));

      final result = await MergeService(
        options: MergeOptions(removeCredits: false),
      ).run(root, outputDir: output, sourceGroups: groups);

      expect(result.successCount, 1);
      expect(
        File(p.join(output.path, 'Arcane.S01E01.chs+eng.ass')).existsSync(),
        isTrue,
      );
    },
  );

  test(
    'self-generated .chs.ass output is skipped but user .chs.ass is kept',
    () async {
      final root = await Directory.systemTemp.createTemp('matcher-selfgen-');
      addTearDown(() => root.delete(recursive: true));
      final mine = File(p.join(root.path, 'Mine.chs.ass'));
      await mine.writeAsString(
        '[Script Info]\n; Script generated by dual-sub-merge\nTitle: Mine\n[Events]\n',
      );
      final theirs = File(p.join(root.path, 'Theirs.chs.ass'));
      await theirs.writeAsString(
        '[Script Info]\nTitle: Handmade\n[Events]\n'
        'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n'
        'Dialogue: 0,0:00:01.00,0:00:02.00,D,,0,0,0,,手写字幕\n',
      );

      final groups = await FileMatcher.scanFiles([mine, theirs]);

      expect(groups, hasLength(1));
      expect(groups.single.chinese?.file.path, theirs.path);
    },
  );

  test('chineseConvert mode writes .chs.ass and rescan ignores it', () async {
    final root = await Directory.systemTemp.createTemp('matcher-zhconvert-');
    addTearDown(() => root.delete(recursive: true));
    final chs = File(p.join(root.path, 'Solo.S01E01.chs.srt'))
      ..writeAsString('1\n00:00:01,000 --> 00:00:02,000\n你好，世界\n');
    final output = Directory(p.join(root.path, 'dual-sub-merged'));

    final groups = await FileMatcher.scanFiles([chs]);
    final result = await MergeService(
      options: MergeOptions(
        removeCredits: false,
        processMode: ProcessMode.chineseConvert,
      ),
    ).run(root, outputDir: output, sourceGroups: groups);

    expect(result.successCount, 1);
    expect(result.convertedChinese, 1);
    final produced = File(p.join(output.path, 'Solo.S01E01.chs.ass'));
    expect(produced.existsSync(), isTrue);
    expect(await produced.readAsString(), contains(',中下HDRipad,'));

    // Output lives beside the input; a rescan must not treat it as a new source.
    final again = await FileMatcher.scanDirectory(root);
    expect(again, hasLength(1));
    expect(again.single.chinese?.file.path, chs.path);
  });

  test('a folder of finished outputs scans to zero groups', () async {
    final root = await Directory.systemTemp.createTemp('matcher-outputs-');
    addTearDown(() => root.delete(recursive: true));
    // What an old "dual-sub-merged" output folder actually contains.
    const header =
        '[Script Info]\n; Script generated by dual-sub-merge\nTitle: X\n[Events]\n'
        'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n'
        'Dialogue: 0,0:00:01.00,0:00:02.00,中下HDRipad,,0,0,0,,你好\n';
    for (final name in ['Ep01.chs+eng.ass', 'Ep02.chs+eng.ass']) {
      await File(p.join(root.path, name)).writeAsString(header);
    }
    await File(p.join(root.path, 'Ep03.chs.ass')).writeAsString(header);

    final files = await FileMatcher.listDirectoryFiles(root);
    expect(files, hasLength(3), reason: 'the files really are on disk');

    for (final f in files) {
      expect(await FileMatcher.isSelfGeneratedOutput(f), isTrue);
    }
    expect(await FileMatcher.scanFiles(files), isEmpty);
  });

  test(
    'explicit videos with the same name in different folders stay distinct',
    () async {
      final root = await Directory.systemTemp.createTemp('matcher-videos-');
      addTearDown(() => root.delete(recursive: true));
      final firstDir = Directory(p.join(root.path, 'first'))..createSync();
      final secondDir = Directory(p.join(root.path, 'second'))..createSync();
      final first = File(p.join(firstDir.path, 'Episode01.mkv'))..createSync();
      final second = File(p.join(secondDir.path, 'Episode01.mkv'))
        ..createSync();

      final groups = await FileMatcher.scanFiles([first, second]);

      expect(groups.where((group) => group.video != null), hasLength(2));
      expect(
        groups.map((group) => group.video?.path).whereType<String>().toSet(),
        {first.path, second.path},
      );
    },
  );
}
